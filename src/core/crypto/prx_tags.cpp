const TagInfo* getTagInfo(uint32_t tag) {
    for (const TagInfo& info : kTagInfo) {
        if (info.tag == tag) {
            return &info;
        }
    }
    return nullptr;
}

const TagInfo2* getTagInfo2(uint32_t tag) {
    for (const TagInfo2& info : kTagInfo2) {
        if (info.tag == tag) {
            return &info;
        }
    }
    return nullptr;
}

